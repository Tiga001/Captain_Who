function numberedAvatar(index) {
  return String(index).padStart(2, '0')
}

function avatarSeed(index) {
  return `${SEED_PREFIX}-${numberedAvatar(index)}`
}

function renderAvatar(style, index) {
  return new Avatar(style, {
    seed: avatarSeed(index),
    size: 128
  }).toString()
}

function validateSvg(svg, label, { requireMetadata = false } = {}) {
  const forbiddenMarkup = /<(?:script|foreignObject)\b/i
  const externalReference = /(?:href|xlink:href)\s*=\s*["'](?!#)[^"']+["']/i
  const externalCssUrl = /url\(\s*["']?(?:https?:|\/\/|data:)/i

  if (!svg.startsWith('<svg ')) {
    throw new Error(`${label} is not an SVG`)
  }
  if (requireMetadata && !svg.includes('<metadata ')) {
    throw new Error(`${label} does not carry the required upstream metadata`)
  }
  if (forbiddenMarkup.test(svg)) {
    throw new Error(`${label} contains executable or foreign markup`)
  }
  if (externalReference.test(svg) || externalCssUrl.test(svg)) {
    throw new Error(`${label} contains an external resource reference`)
  }
}

function createManifest() {
  const generatedEntries = styles.flatMap(({ directory, filePrefix }) =>
    Array.from({ length: AVATAR_COUNT_PER_STYLE }, (_, offset) => {
      const number = numberedAvatar(offset + 1)
      return `  new URL('./${directory}/${filePrefix}-${number}.svg', import.meta.url).href`
    })
  )
  const fluentEntries = fluentEmojiFiles.map(
    (filename) => `  new URL('./fluent-emoji/${filename}', import.meta.url).href`
  )
  const entries = [...generatedEntries, ...fluentEntries]

  return `// Generated by scripts/generate-agent-avatars.mjs using DiceBear ${DICEBEAR_VERSION}\n// and vendored Fluent Emoji assets from commit ${FLUENT_EMOJI_COMMIT}.\n// Keep entries in this stable order so deterministic avatar assignments remain valid.\nexport const AGENT_AVATAR_URLS = [\n${entries.join(',\n')}\n] as const\n\nexport const AGENT_AVATAR_COUNT = AGENT_AVATAR_URLS.length\n`
}

async function writeOrCheck(path, content) {
  if (checkOnly) {
    let existing
    try {
      existing = await readFile(path, 'utf8')
    } catch {
      throw new Error(`Missing generated file: ${relative(repositoryRoot, path)}`)
    }

    if (existing !== content) {
      throw new Error(`Generated file is stale: ${relative(repositoryRoot, path)}`)
    }
    return
  }

  await mkdir(dirname(path), { recursive: true })
  await writeFile(path, content, 'utf8')
}

async function assertExactStyleFiles(definition) {
  const directory = join(assetsDirectory, definition.directory)
  const expected = Array.from(
    { length: AVATAR_COUNT_PER_STYLE },
    (_, offset) => `${definition.filePrefix}-${numberedAvatar(offset + 1)}.svg`
  )
  const actual = (await readdir(directory)).filter((name) => name.endsWith('.svg')).sort()

  if (actual.join('\n') !== expected.join('\n')) {
    throw new Error(
      `${definition.filePrefix} asset filenames differ from the fixed ${AVATAR_COUNT_PER_STYLE}-file manifest`
    )
  }
}

const hashes = []
const styleSummaries = []

for (const definition of styles) {
  const style = new Style(definition.definition)
  const styleHashes = new Set()
  for (let index = 1; index <= AVATAR_COUNT_PER_STYLE; index += 1) {
    const number = numberedAvatar(index)
    const outputPath = join(
      assetsDirectory,
      definition.directory,
      `${definition.filePrefix}-${number}.svg`
    )
    const svg = renderAvatar(style, index)
    validateSvg(svg, `${definition.filePrefix}-${number}.svg`, { requireMetadata: true })
    await writeOrCheck(outputPath, svg)
    const hash = createHash('sha256').update(svg).digest('hex')
    if (styleHashes.has(hash)) {
      throw new Error(`${definition.filePrefix} generated a duplicate avatar at ${number}`)
    }
    styleHashes.add(hash)
    hashes.push(hash)
  }
  await assertExactStyleFiles(definition)
  styleSummaries.push(`${definition.filePrefix}=${styleHashes.size} unique`)
}

const fluentEmojiDirectory = join(assetsDirectory, 'fluent-emoji')
const actualFluentFiles = (await readdir(fluentEmojiDirectory))
  .filter((name) => name.endsWith('.svg'))
  .sort()
if (actualFluentFiles.join('\n') !== fluentEmojiFiles.join('\n')) {
  throw new Error('Fluent Emoji asset filenames differ from the fixed 48-file manifest')
}

const fluentHashes = []
for (const filename of fluentEmojiFiles) {
  const svg = await readFile(join(fluentEmojiDirectory, filename), 'utf8')
  validateSvg(svg, `fluent-emoji/${filename}`)
  fluentHashes.push(createHash('sha256').update(svg).digest('hex'))
}
if (new Set(fluentHashes).size !== fluentEmojiFiles.length) {
  throw new Error('Fluent Emoji avatar pool contains duplicate assets')
}
const fluentAggregateHash = createHash('sha256').update(fluentHashes.join('\n')).digest('hex')
if (fluentAggregateHash !== FLUENT_EMOJI_AGGREGATE_SHA256) {
  throw new Error(
    `Fluent Emoji aggregate SHA-256 changed: expected ${FLUENT_EMOJI_AGGREGATE_SHA256}, received ${fluentAggregateHash}`
  )
}

await writeOrCheck(manifestPath, createManifest())

const aggregateHash = createHash('sha256').update(hashes.join('\n')).digest('hex')
console.log(
  `${checkOnly ? 'Verified' : 'Generated'} ${hashes.length + fluentEmojiFiles.length} agent avatars: DiceBear ${DICEBEAR_VERSION} (${styleSummaries.join(', ')}; aggregate ${aggregateHash}) and Fluent Emoji ${FLUENT_EMOJI_COMMIT.slice(0, 8)} (${fluentEmojiFiles.length} unique; aggregate ${fluentAggregateHash})`
)
