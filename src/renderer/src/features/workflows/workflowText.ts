export type WorkflowText = (key: WorkflowTextKey) => string
export function workflowText(language?: string): WorkflowText {
  const dictionary = language?.startsWith('zh') ? chinese : english
  return (key) => dictionary[key]
}
export function workflowIssueText(code: string, text: WorkflowText): string {
  const key = `issue_${code}` as WorkflowTextKey
  return key in english ? text(key) : text('issue_unknown')
}
